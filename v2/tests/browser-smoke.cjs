const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.KGT_URL || 'http://127.0.0.1:8511');
 await page.getByRole('button',{name:'01 프로젝트 공정 진행 현황을 알려줘'}).waitFor();
 await page.screenshot({path:'/tmp/kgt-desktop.png',fullPage:true});
 await page.getByLabel('문서 검색').fill('레이저');
 await page.getByRole('button',{name:'검색',exact:true}).click();
 await page.getByRole('button',{name:/KGT-KB-006/}).click();
 await page.getByRole('dialog').getByText(/레이저/).first().waitFor();
 await page.getByLabel('닫기',{exact:true}).click();
 await page.getByRole('button',{name:/자재·재고/}).click();
 await page.getByRole('dialog').locator('table').waitFor();
 await page.getByLabel('닫기',{exact:true}).click();
 await page.getByLabel('프로젝트',{exact:true}).selectOption('KGT-26001');
 await page.getByLabel('질문 입력').fill('자재 LOT와 재고 상태를 알려줘');
 await page.getByLabel('질문 보내기').click();
 await page.locator('.message.assistant').waitFor();
 await page.locator('.message summary').click();
 if (!(await page.locator('.message table').innerText()).includes('KGT-26001')) throw Error('Project evidence missing');
 await page.getByLabel('프로젝트',{exact:true}).selectOption('KGT-26002');
 if (await page.locator('.message').count()) throw Error('Project reset failed');
 await page.getByRole('button',{name:'07 FAT 불합격 결과를 보여줘'}).click();
 await page.locator('.message.assistant').waitFor();
 await page.getByRole('button',{name:'새 대화'}).click();
 await page.locator('.past').first().click();
 await page.locator('.message.assistant').waitFor();
 await page.getByRole('button',{name:'새 대화'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/kgt-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth))throw Error('Mobile horizontal overflow');
 await page.getByRole('button',{name:'자료',exact:true}).click();
 await page.getByRole('button',{name:/KGT-KB-006/}).click();
 await page.getByLabel('닫기',{exact:true}).click();
 await page.getByRole('button',{name:'질문',exact:true}).click();
 await page.getByRole('button',{name:'07 FAT 불합격 결과를 보여줘'}).click();
 await page.locator('.message.assistant').waitFor();
 await page.locator('.message summary').click();
 await page.screenshot({path:'/tmp/kgt-mobile-evidence.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth))throw Error('Evidence horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Desktop and 390px: documents, tables, direct/recommended/history questions, project reset, evidence: PASS');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
